def enum(enum_cls: type[StrEnum]) -> sa.Enum:
    # Se guarda como VARCHAR (native_enum=False): agregar un valor nunca exige una migración con ALTER TYPE.
    return sa.Enum(
        enum_cls,
        native_enum=False,
        values_callable=lambda e: [m.value for m in e],
        length=32,
        validate_strings=True,
        name=enum_cls.__name__.lower(),
    )


